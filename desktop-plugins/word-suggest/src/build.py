"""Assemble ../plugin.js from engine.mjs + words.txt + ui.js.

Hermes Desktop loads a plugin as one uncompiled file that may import only the
SDK and React, so the parts are joined here. Run after editing anything in src/:
    python build.py
"""

import json
import re
from pathlib import Path

SRC = Path(__file__).resolve().parent
HEADER = """// GENERATED by src/build.py from src/engine.mjs, src/words.txt and src/ui.js. Edit those, not this file.
// Word list: the 36,000 most frequent English words from the FrequencyWords project
// (hermitdave/FrequencyWords, built from OpenSubtitles; CC BY-SA 4.0).
import { host, Button, Switch } from '@hermes/plugin-sdk'
import { useState } from 'react'
import { jsx, jsxs } from 'react/jsx-runtime'

"""

engine = re.sub(r"^export ", "", (SRC / "engine.mjs").read_text(encoding="utf-8"), flags=re.M)
words = (SRC / "words.txt").read_text(encoding="utf-8").strip()
ui = (SRC / "ui.js").read_text(encoding="utf-8")
out = SRC.parent / "plugin.js"
out.write_text(f"{HEADER}const WORDS = {json.dumps(words)}\n\n{engine}\n{ui}", encoding="utf-8", newline="\n")
print(f"wrote {out} ({out.stat().st_size // 1024} KB)")
